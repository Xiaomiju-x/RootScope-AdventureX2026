/** Configure pins as
        * Analog
        * Input
        * Output
        * EVENT_OUT
        * EXTI
*/
void MX_GPIO_Init(void)
{

  GPIO_InitTypeDef GPIO_InitStruct = {0};

  /* GPIO Ports Clock Enable */
  __HAL_RCC_GPIOD_CLK_ENABLE();
  __HAL_RCC_GPIOA_CLK_ENABLE();
  __HAL_RCC_GPIOB_CLK_ENABLE();

  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(GPIOA, Z_INA_Pin|Z_INB_Pin|Z_INC_Pin|Z_IND_Pin
                          |UNUSED_PA4_Pin|UNUSED_PA5_Pin
                          |UNUSED_PA6_Pin|UNUSED_PA7_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pin Output Level */
  /* Active-low relay: release PB6 before enabling open-drain mode (pump off). */
  HAL_GPIO_WritePin(GPIOB, PUMP_Pin, GPIO_PIN_SET);

  /* Keep retired PA4..PA7 outputs low so an old connected driver stays off. */
  GPIO_InitStruct.Pin = Z_INA_Pin|Z_INB_Pin|Z_INC_Pin|Z_IND_Pin
                          |UNUSED_PA4_Pin|UNUSED_PA5_Pin
                          |UNUSED_PA6_Pin|UNUSED_PA7_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);

  /*Configure GPIO pin : PB6 (the only fitted pump relay). PB7 is unused. */
  GPIO_InitStruct.Pin = PUMP_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_OD;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);

}

